/**
 * 줄간격 — **한글은 lineHeight를 반드시 명시한다.**
 *
 * 안드로이드 기본 줄간격은 폰트 크기의 약 1.2배다. 라틴 문자엔 충분하지만 한글은
 * **받침이 아래로 내려와** 그 값에서 위아래 줄이 서로 붙어 보인다(2026-07-30 회장 지적:
 * "모든 페이지에 줄간격이 너무 좁다"). 당시 `fontSize` 218곳 중 `lineHeight`가 있는 건
 * 23곳뿐이었다.
 *
 * 쓰는 법 — `lineHeight: leading(15)` 처럼 폰트 크기를 넣는다. 크기별 배수는 아래 규칙:
 *  - 본문·설명·라벨(≤17) = **1.55배**. 두 줄 이상 흐르는 텍스트가 여기 다 들어간다.
 *  - 제목(18~28) = **1.35배**. 큰 글자는 배수가 크면 오히려 흩어진다.
 *  - 큰 숫자(29+, 주로 `FONT_DISPLAY`) = **1.1배**. 숫자는 받침이 없고, 여기에 본문 배수를
 *    주면 히어로 카드 높이가 통째로 밀려 첫 뷰포트가 깨진다.
 *
 * ⚠️ 배지·칩 안의 한 줄 텍스트나 단위(`km`·`회`)에는 굳이 주지 않는다 — 줄이 하나뿐이라
 *    시각 효과는 없고 박스 높이만 커져서 정렬이 흔들린다.
 */
export function leading(fontSize: number): number {
  const ratio = fontSize >= 29 ? 1.1 : fontSize >= 18 ? 1.35 : 1.55;
  return Math.round(fontSize * ratio * 10) / 10;
}

